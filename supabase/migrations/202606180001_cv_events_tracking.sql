create table if not exists public.cv_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  session_id text,
  cv_id uuid,
  event_name text not null,
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

alter table public.cv_events enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'cv_events'
      and policyname = 'Allow cv event inserts'
  ) then
    create policy "Allow cv event inserts"
      on public.cv_events
      for insert
      to anon, authenticated
      with check (true);
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'cv_events'
      and policyname = 'Users can read their own cv events'
  ) then
    create policy "Users can read their own cv events"
      on public.cv_events
      for select
      to authenticated
      using (auth.uid() = user_id);
  end if;
end
$$;

alter table public.cvs
  add column if not exists download_count integer not null default 0,
  add column if not exists last_downloaded_at timestamptz;

create index if not exists cv_events_user_id_idx on public.cv_events (user_id);
create index if not exists cv_events_session_id_idx on public.cv_events (session_id);
create index if not exists cv_events_event_name_idx on public.cv_events (event_name);
create index if not exists cv_events_created_at_idx on public.cv_events (created_at desc);
